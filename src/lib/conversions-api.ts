/**
 * Server-side Meta Conversions API for Purchase events
 * Provides deduplication via event_id and enhanced data sharing
 */

import crypto from "crypto";

interface ConversionsAPIPayload {
  data: Array<{
    event_name: string;
    event_time: number;
    event_id: string;
    action_source: "website" | "app" | "email" | "other";
    event_source_url: string;
    user_data: {
      em?: string; // hashed email
      ph?: string; // hashed phone
      fn?: string; // hashed first name
      ln?: string; // hashed last name
      ct?: string; // hashed city
      st?: string; // hashed state
      zp?: string; // hashed zip
      country?: string;
      client_ip_address?: string;
      client_user_agent?: string;
      fbc?: string; // Facebook Click ID
      fbp?: string; // Facebook Browser ID
    };
    custom_data: {
      currency: string;
      value: number;
      content_ids: string[];
      content_type: "product" | "product_group";
      content_name?: string;
      content_category?: string;
      num_items?: number;
      order_id?: string;
    };
  }>;
}

function sha256(data: string): string {
  return crypto.createHash("sha256").update(data.trim().toLowerCase()).digest("hex");
}

function hashIfPresent(value?: string | null): string | undefined {
  if (!value) return undefined;
  return sha256(value);
}

interface PurchaseEventData {
  orderNumber: string;
  email: string;
  phone: string;
  name: string;
  address: {
    street: string;
    city: string;
    state: string;
    pincode: string;
  };
  items: Array<{
    variant_id: number;
    quantity: number;
    productName?: string;
    price: number;
  }>;
  total: number;
  eventId: string; // Generated by client for deduplication
  clientIp?: string;
  clientUserAgent?: string;
  fbc?: string;
  fbp?: string;
}

/**
 * Send Purchase event to Meta Conversions API
 * Returns true if successful, false if failed (logged but not thrown)
 */
export async function sendPurchaseToConversionsAPI(
  data: PurchaseEventData
): Promise<boolean> {
  const accessToken = process.env.META_CONVERSIONS_API_TOKEN;
  const pixelId = process.env.META_PIXEL_ID;
  const datasetId = process.env.META_DATASET_ID; // Optional: for CAPI Gateway

  if (!accessToken || !pixelId) {
    console.log("[Conversions API] Not configured (missing META_CONVERSIONS_API_TOKEN or META_PIXEL_ID)");
    return false;
  }

  // Parse name into first/last
  const nameParts = data.name.trim().split(/\s+/);
  const firstName = nameParts[0] || "";
  const lastName = nameParts.slice(1).join(" ") || "";

  // Prepare user data with hashed PII
  const userData = {
    em: hashIfPresent(data.email),
    ph: hashIfPresent(data.phone),
    fn: hashIfPresent(firstName),
    ln: hashIfPresent(lastName),
    ct: hashIfPresent(data.address.city),
    st: hashIfPresent(data.address.state),
    zp: hashIfPresent(data.address.pincode),
    country: "IN",
    client_ip_address: data.clientIp,
    client_user_agent: data.clientUserAgent,
    fbc: data.fbc,
    fbp: data.fbp,
  };

  // Prepare custom data
  const contentIds = data.items.map((item) => String(item.variant_id));
  const contentNames = data.items.map((item) => item.productName || `Variant ${item.variant_id}`).join(", ");

  const customData = {
    currency: "INR",
    value: data.total,
    content_ids: contentIds,
    content_type: "product" as const,
    content_name: contentNames,
    num_items: data.items.reduce((sum, item) => sum + item.quantity, 0),
    order_id: data.orderNumber,
  };

  const payload: ConversionsAPIPayload = {
    data: [
      {
        event_name: "Purchase",
        event_time: Math.floor(Date.now() / 1000),
        event_id: data.eventId,
        action_source: "website",
        event_source_url: `${process.env.NEXT_PUBLIC_SITE_URL ?? "https://www.indicoreoriginals.me"}/checkout`,
        user_data: userData,
        custom_data: customData,
      },
    ],
  };

  // Determine endpoint - use CAPI Gateway if datasetId provided, else direct to Graph API
  const endpoint = datasetId
    ? `https://graph.facebook.com/v19.0/${datasetId}/events`
    : `https://graph.facebook.com/v19.0/${pixelId}/events`;

  try {
    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify(payload),
    });

    const result = await response.json();

    if (!response.ok) {
      console.error("[Conversions API] Error:", result);
      return false;
    }

    console.log("[Conversions API] Purchase event sent successfully:", {
      event_id: data.eventId,
      order_number: data.orderNumber,
      events_received: result.events_received,
    });

    return true;
  } catch (error) {
    console.error("[Conversions API] Network error:", error);
    return false;
  }
}

/**
 * Generate a unique event ID for deduplication
 * Format: timestamp-random (matches client-side generation)
 */
export function generateEventId(): string {
  return `${Date.now()}-${crypto.randomBytes(8).toString("hex")}`;
}